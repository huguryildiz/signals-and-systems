/* Packs the JPEGs in this folder into build/src/77_images.js as data URIs, so the
   artifact stays a single file. Run after adding or replacing an image:
   node build/img/pack.js */
const fs = require('fs'), path = require('path');
const files = fs.readdirSync(__dirname).filter(f => f.endsWith('.jpg')).sort();
const rows = files.map(f => `  ${JSON.stringify(f.replace(/\.jpg$/, ''))}: 'data:image/jpeg;base64,${
  fs.readFileSync(path.join(__dirname, f)).toString('base64')}'`);
const out = `/* generated by build/img/pack.js; do not edit */\nconst IMG = {\n${rows.join(',\n')}\n};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', '77_images.js'), out);
console.log('packed', files.length, 'images,', (out.length / 1024).toFixed(0), 'KB');
